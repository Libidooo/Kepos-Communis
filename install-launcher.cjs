// Repair the Windows PATH entry without embedding Unicode paths in batch source.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

try {
 if (process.platform !== 'win32') throw Error('This launcher installer requires Windows');
 if (!process.env.KEPOS_BIN_DIR && !process.env.APPDATA) throw Error('APPDATA is unavailable; set KEPOS_BIN_DIR');
 const target = path.resolve(process.env.KEPOS_BIN_DIR || path.join(process.env.APPDATA, 'npm'));
 const entry = fs.realpathSync(path.join(__dirname, 'kepos.cjs'));
 const literal = JSON.stringify(entry).replace(/[^\x00-\x7f]/g, character => '\\u' + character.charCodeAt(0).toString(16).padStart(4, '0'));
 const files = {
  'kepos-launcher.cjs': `// Generated by Kepos. Unicode paths are escaped for code-page independence.\nconst entry = ${literal};\nprocess.argv[1] = entry;\nrequire(entry);\n`,
  'kepos.cmd': '@echo off\r\nnode "%~dp0kepos-launcher.cjs" %*\r\nexit /b %errorlevel%\r\n',
 };
 if (process.argv.includes('--check')) {
  let ok = true;
  for (const [name, content] of Object.entries(files)) {
   const file = path.join(target, name);
   const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content;
   console.log((same ? 'MATCH ' : 'DIFF  ') + file);
   ok &&= same;
  }
  process.exitCode = ok ? 0 : 1;
 } else {
  const backup = path.join(__dirname, 'recovery', 'launcher-' + crypto.randomUUID());
  const previous = new Map();
  for (const name of Object.keys(files)) {
   const file = path.join(target, name);
   if (fs.existsSync(file)) {
    const content = fs.readFileSync(file);
    previous.set(name, content);
    fs.mkdirSync(backup, { recursive: true });
    fs.writeFileSync(path.join(backup, name), content);
   }
  }
  fs.mkdirSync(target, { recursive: true });
  const written = [];
  try {
   // Write the JS bridge first so the batch entry never points at a missing bridge.
   for (const [name, content] of Object.entries(files)) {
    written.push(name);
    fs.writeFileSync(path.join(target, name), content, 'ascii');
   }
  } catch (error) {
   for (const name of written.reverse()) {
    try {
     if (previous.has(name)) fs.writeFileSync(path.join(target, name), previous.get(name));
     else if (fs.existsSync(path.join(target, name))) fs.unlinkSync(path.join(target, name));
    } catch (restoreError) { console.error('Restore failed for ' + name + ': ' + restoreError.message); }
   }
   console.error('Recovery backup: ' + backup);
   throw error;
  }
  console.log('Installed Kepos command: ' + path.join(target, 'kepos.cmd'));
  console.log('Workspace entry: ' + entry);
  if (previous.size) console.log('Previous launcher backed up: ' + backup);
 }
} catch (error) {
 console.error('Kepos launcher installation failed: ' + error.message);
 process.exitCode = 1;
}
